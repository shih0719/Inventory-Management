export function tagLabel(tagName: string, lang: Lang): string {
  const t = L[lang];
  const map: Record<string, string> = {
    INBOUND: t.inboundLbl,
    OUTBOUND: t.outboundLbl,
    ADJUST: t.adjustLbl,
    RETURN: t.returnLbl,
    INTERNAL: t.internalLbl,
  };
  return map[tagName] || tagName;
}

